/// Each write-queue command is invoked by the name it is registered under.
///
/// A renamed command is not a compile error on either side: Tauri resolves it
/// by string at run time and answers "command not found" to a webview that has
/// already opened the dialog. The Rust half of the pair is
/// `wiring.rs::every_command_is_in_the_handler_list`, which proves the
/// registration exists; this proves the mirror calls *that* name.
#[test]
fn the_mirror_invokes_the_write_queue_commands_by_their_registered_names() {
    for command in [
        "pending_writes",
        "write_queue_counts",
        "flush_writes",
        "apply_held_write",
        "amend_write",
        "discard_write",
    ] {
        assert!(
            MIRROR.contains("invoke<"),
            "the mirror no longer invokes anything"
        );
        assert!(
            MIRROR.contains(&format!("\"{command}\"")),
            "app/src/lib/ipc/sources.ts never invokes {command:?}"
        );
        assert!(
            SOURCES_COMMANDS.contains(&format!("pub async fn {command}")),
            "commands/sources.rs no longer declares {command:?}"
        );
    }
}

