/// `AuthState`'s **members**, not just the shape of the struct that carries it.
///
/// `assert_shape` above pins `CredentialHealth.state` as a *key*; nothing pinned
/// what may be in it. The launcher branches on those spellings --
/// `app/src/lib/shell/health.svelte.ts` builds a total `Record<AuthState, boolean>`
/// over them to decide which states mean "a human must act" -- so a variant
/// added on the Rust side with no member here fell through to "not actionable"
/// silently, which is the drift #27 round 2 recorded and #37 asked to close.
///
/// The Rust side is `AuthState::ALL`, generated by `closed_vocabulary!` from the
/// same variant list as the enum, so it cannot be the half that goes stale; the
/// TypeScript side is read out of the mirror rather than listed here.
#[test]
fn the_auth_state_union_matches_the_rust_enum() {
    let mut declared = knobas_sync::mirror::declared_union(MIRROR, "AuthState");
    declared.sort();
    let mut rust: Vec<String> = knobas_sync::config::AuthState::ALL
        .iter()
        .map(|state| state.as_str().to_owned())
        .collect();
    rust.sort();
    assert_eq!(
        declared, rust,
        "app/src/lib/ipc/sources.ts's `AuthState` union and `knobas_sync::AuthState` \
         disagree; the launcher's actionable-state table is built over the union, so a \
         state missing from it is a state the UI silently treats as fine"
    );
}

