        assert!(built.sql.contains("and false"), "{}", built.sql);
        // And the two branches cannot read each other's rows.
        assert!(built.sql.contains("where p.corpus = 0"), "{}", built.sql);
        assert!(built.sql.contains("where p.corpus = 1"), "{}", built.sql);
