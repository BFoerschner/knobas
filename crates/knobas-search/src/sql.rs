//! The one module in knobas that assembles a SQL statement at runtime.
//!
//! Roadmap §4 gotcha 2, verbatim: *"sqlx 0.9: dynamic SQL needs
//! `AssertSqlSafe`; keep it in one reviewed query-builder module. Never bind
//! `tsquery` -- bind text into `websearch_to_tsquery('english', $1)`, compute
//! the tsquery once as a FROM item. Never map `tsvector` to `String`."* This is
//! that module, and `tests/it/sql_containment.rs` fails the build if anything else
//! in the crate so much as names the type.
//!
//! # Why the confinement holds
//!
//! Three things, in order of how much they are worth:
//!
//! 1. **Types.** [`SearchSql`]'s fields are private and the builders in this
//!    module are its only constructors, so no caller anywhere can hand
//!    [`query_as_with`] a string it made up. The escape hatch is not merely
//!    discouraged, it is unreachable.
//! 2. **The `Corpus` invariant.** Every fragment spliced into the statement is
//!    a `&'static str` from [`crate::corpus`]; every value -- every word the
//!    user typed, every source id, every kind, every limit -- travels as a
//!    bind, and the *only* way to add one is [`Builder::param`], which returns
//!    the placeholder that reads it. A placeholder therefore cannot drift from
//!    its argument. The one piece of runtime-formatted text is the corpus
//!    index, a loop counter over the caller's own slice.
//! 3. **A test**, for the day someone in a hurry adds a fourth thing.
//!
//! # The shape of the statement, and why
//!
//! ```sql
//! with q as (...),                 -- the tsquery, computed once
//!      m as materialized (...),    -- one narrow row per *match*
//!      totals as (...),            -- per-kind counts, over every match
//!      top as (...),               -- rank within kind
//!      picked as (...),            -- the page
//!      detail as (...)             -- titles and excerpts, page only
//! select ... from totals left join detail ...
//! ```
//!
//! Four properties are load-bearing:
//!
//! * **`m` is deliberately narrow** -- entity id, kind, rank, whether the row
//!   is named what was typed, updated-at and nothing else. It holds one row
//!   per match, which for a common word is thousands; carrying titles and
//!   bodies through it is what turns a 20 ms search into a 200 ms one.
//! * **Exactly one match scan.** `m` is `materialized` because both `totals`
//!   and `top` read it, and the alternative is scanning the index twice.
//! * **`totals` LEFT JOIN `detail`**, so every matching kind comes back even
//!   when the global `limit` left it no row: `ResultGroup.total` is then a true
//!   count and not a page size. A kind with `total > 0` and no hit is a
//!   legitimate row, and the columns of such a row are **null** -- the caller's
//!   `FromRow` must read them as `Option`.
//! * **`ts_headline` runs after the limit.** It re-parses the document text per
//!   row, and running it over the match set instead of over the page is the
//!   single most expensive mistake available here.
//!
//! # The second statement, and why it is a second one
//!
//! [`saved_summary_sql`] (#506) answers *how many rows are in this saved list,
//! and how fresh is the newest of them* for every saved list at once. It is a
//! separate builder rather than a mode of [`search_sql`] because it shares
//! exactly one thing with a search -- the `where` clause -- and none of the six
//! stages above: no ranking, no per-kind cap, no page, no titles, no excerpts.
//! The one thing they do share is generated by one function,
//! [`corpus_predicates`], so the number on the rail and the rows behind it
//! cannot come from two different readings of the same query.
//!
//! This replaces the contract seed's two statements, whose per-kind total was a
//! `count(*) over (partition by kind)` -- a second window partition, and
//! therefore a second full sort of every matching row, on the launcher's hot
//! path (M0 carry-over). `totals` is one grouped aggregate over the same
//! materialized scan.

use std::fmt::Write as _;

use sqlx::postgres::{PgArguments, PgRow};
use sqlx::query::QueryAs;
use sqlx::{FromRow, Postgres};

use crate::corpus::Corpus;
use crate::query::{EffectiveFilters, WordAlternative};

/// One value bound into a generated statement.
///
/// Deliberately closed and deliberately small: every variant here is something
/// the builder actually binds, so a variant nobody constructs is a variant
/// nobody has to review.
#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum Bind {
    /// The raw search text, and the `ts_headline` options.
    Text(String),
    /// A `text[]` for an `= any(...)` predicate.
    Texts(Vec<String>),
    /// `make_interval(days => ...)`, which takes an `int4`.
    I32(i32),
    /// Row counts: `row_number()` yields `bigint`, and so does `limit`.
    I64(i64),
    /// The declarations `under:` reads the parent through, bound as one
    /// `jsonb` through `Declarations::as_param`, the one place that wraps
    /// them, as every path-driven read does.
    Json(sqlx::types::Json<serde_json::Value>),
}

/// A generated statement and the arguments that go with it.
///
/// The fields are private and the two builders in this module -- [`search_sql`]
/// and [`saved_summary_sql`] -- are its only constructors. That is not
/// tidiness: it is what makes "runtime SQL is confined to this module" a
/// property of the type system rather than of a convention, and adding a
/// builder does not weaken it, because a caller still cannot hand
/// [`query_as_with`] a string of its own.
#[derive(Debug, Clone)]
pub struct SearchSql {
    sql: String,
    binds: Vec<Bind>,
}

impl SearchSql {
    /// The generated statement, for tests and for tracing.
    #[must_use]
    pub fn sql(&self) -> &str {
        &self.sql
    }

    /// How many arguments the statement expects.
    #[must_use]
    pub fn bind_count(&self) -> usize {
        self.binds.len()
    }
}

/// Assemble the launcher's query.
///
/// * `corpora` -- the relations to search. M1 passes `&[&LIVE_ITEM]`; more than
///   one becomes a `union all` inside the match CTE.
/// * `text` -- the search terms, or `None` for **browse mode**: no ranking, no
///   excerpts, ordered by recency. A browse with no filters at all is refused
///   upstream rather than counting the whole corpus.
/// * `prefix_last` -- whether the last word is still being typed and should
///   match as a prefix.
/// * `per_group` -- how many rows one kind may contribute, so a flood of
///   tickets cannot push every build off the page.
/// * `limit` -- the total number of rows returned.
#[must_use]
pub fn search_sql(
    corpora: &[&Corpus],
    text: Option<&str>,
    prefix_last: bool,
    filters: &EffectiveFilters,
    per_group: u32,
    limit: u32,
) -> SearchSql {
    let mut builder = Builder::default();

    // Binds are allocated in the order their placeholders first appear in the
    // statement below. That is not cosmetic: it is what keeps `$1..$n` dense
    // and in order, which `placeholders_are_numbered_in_bind_order` pins.
    let tsquery = text.map(|raw| builder.param(Bind::Text(raw.to_owned())));
    let bound = bind_filters(&mut builder, filters);
    let per_group = builder.param(Bind::I64(i64::from(per_group)));
    let limit = builder.param(Bind::I64(i64::from(limit)));
    let headline_opts = text.map(|_| builder.param(Bind::Text(crate::snippet::headline_options())));
    // Every row's path line reads the parent its kind declares (#596), so the
    // declarations are bound for every search -- once: an `under:` query has
    // already bound them, and the detail stage reads that same placeholder.
    let path_declarations = match &bound.declarations {
        Some(declarations) => declarations.clone(),
        None => builder.param(Bind::Json(filters.declarations.as_param())),
    };

    let mut sql = String::from("with\n");

    if let Some(tsquery) = &tsquery {
        // Computed ONCE, as a FROM item, and never bound as a tsquery
        // (roadmap §4 gotcha 2): the match, the rank and the headline all read
        // this one value.
        sql.push_str("q as not materialized (\n  select ");
        if prefix_last {
            // What makes the box answer while the word is still being typed.
            // `websearch_to_tsquery` output is already a well-formed, quoted
            // tsquery, so appending ':*' to its *text* and casting back turns
            // only the last lexeme into a prefix. The guard is for the empty
            // case -- a query of nothing but stopwords yields the empty
            // tsquery, and ':*' on its own is a syntax error.
            sql.push_str(concat!(
                "case when t.tsq::text = '' then null::tsquery\n",
                "              else (t.tsq::text || ':*')::tsquery end as tsq,\n",
                // The same words with none of them a prefix: what a row is
                // ranked by when it holds the last word whole (`RANK_WHOLE`).
                "         t.tsq as whole,\n"
            ));
        } else {
            sql.push_str("t.tsq as tsq,\n");
        }
        // The typed words as `to_tsvector` lexes a name, sorted and distinct,
        // for `NAMED`: one array per search, compared against each match. It
        // must lex exactly as `NAMED` does, or no row is ever named.
        let _ = writeln!(
            sql,
            "         tsvector_to_array(to_tsvector('english', {tsquery})) as words"
        );
        let _ = writeln!(
            sql,
            "    from (select websearch_to_tsquery('english', {tsquery}) as tsq) t\n),"
        );
    }

    // A ticket key's declared paths, resolved once for the statement (#811),
    // and what `reach:` reaches, walked once for every corpus (#1653).
    sql.push_str(&field_paths(&bound));
    sql.push_str(&reaches(&bound));

    // One narrow row per match. MATERIALIZED because `totals` and `top` both
    // read it and the scan must happen once.
    sql.push_str("m as materialized (\n");
    for (index, corpus) in corpora.iter().enumerate() {
        if index > 0 {
            sql.push_str("  union all\n");
        }
        let rank = match (text.is_some(), prefix_last) {
            (true, true) => RANK_WHOLE.replace("{fts}", corpus.fts),
            (true, false) => format!("ts_rank_cd({}, q.tsq)", corpus.fts),
            (false, _) => "0::real".to_owned(),
        };
        // What a corpus stores (#1650) it is not lexed for, per match.
        let named = match (text, corpus.named) {
            (None, _) => "false".to_owned(),
            (Some(_), Some(stored)) => stored.to_owned(),
            (Some(_), None) => NAMED.replace("{title}", corpus.title),
        };
        let _ = writeln!(
            sql,
            "  select {} as entity_id, {} as kind, {rank} as rank, {named} as named,\n         {} as item_updated_at, {index} as corpus",
            corpus.entity_id, corpus.kind, corpus.updated_at
        );
        let _ = write!(sql, "    from {}", corpus.relation);
        if text.is_some() {
            sql.push_str(" cross join q");
        }
        sql.push('\n');

        let predicates = corpus_predicates(corpus, text.is_some().then_some("q.tsq"), &bound);
        if !predicates.is_empty() {
            let _ = writeln!(sql, "   where {}", predicates.join("\n     and "));
        }
    }
    sql.push_str("),\n");

    // The true per-kind count, over every match rather than over the page.
    sql.push_str("totals as (select kind, count(*) as kind_total from m group by kind),\n");

    // One ordering, spelled three times with different qualifiers: within the
    // kind (window), across the page, and across the joined result. They must
    // agree, or the row a group header counts is not the row it shows.
    let ranked = text.is_some();
    let ordering = order_by("", ranked, false);

    let _ = writeln!(
        sql,
        "top as (\n  select m.*, row_number() over (partition by m.kind order by {}) as rn\n    from m\n),",
        order_by("m.", ranked, false)
    );
    // One kind cannot flood the box (rn), and the whole answer is bounded
    // (limit) before anything expensive touches it.
    let _ = writeln!(
        sql,
        "picked as (\n  select * from top where rn <= {per_group}\n   order by {ordering}\n   limit {limit}\n),"
    );

    // Titles and excerpts, on the rows that survived and no others.
    sql.push_str("detail as (\n");
    for (index, corpus) in corpora.iter().enumerate() {
        if index > 0 {
            sql.push_str("  union all\n");
        }
        let snippet = match &headline_opts {
            Some(opts) => format!(
                "ts_headline('english', {}, q.tsq, {opts})",
                corpus.headline_text
            ),
            None => "null::text".to_owned(),
        };
        let _ = writeln!(
            sql,
            "  select p.kind as kind, p.entity_id as entity_id, p.rank as rank, p.named as named,\n         p.item_updated_at as item_updated_at,\n         {} as source_id, {} as title, {} as synced_at,\n         {} as path, {} as state,\n         {snippet} as snippet",
            corpus.source_id, corpus.title, corpus.synced_at, corpus.path, corpus.state
        );
        let _ = write!(sql, "    from picked p\n    join {}", corpus.relation);
        let _ = write!(sql, " on {} = p.entity_id", corpus.entity_id);
        if let Some(scope) = corpus.scope {
            let _ = write!(sql, " and {scope}");
        }
        sql.push('\n');
        // `pd` is the one row a corpus's `path` reads the declarations from,
        // as `ud` is for `under:` -- so the expression stays a `&'static str`
        // and the declarations stay a bind.
        let _ = writeln!(
            sql,
            "    cross join (select {path_declarations}::jsonb as d) pd"
        );
        if text.is_some() {
            sql.push_str("    cross join q\n");
        }
        // The discriminator, so two corpora that happen to share an entity id
        // cannot cross-join into each other's detail rows.
        let _ = writeln!(sql, "   where p.corpus = {index}");
    }
    sql.push_str(")\n");

    // A kind the limit cut has no detail row, so every `d.` column here is
    // null for it -- `nulls last` keeps those group headers at the end of
    // their kind rather than at the front of it.
    let _ = write!(
        sql,
        "select t.kind as group_kind, t.kind_total as kind_total,\n       d.entity_id as entity_id, d.source_id as source_id, d.title as title,\n       d.item_updated_at as updated_at, d.synced_at as synced_at,\n       d.path as path, d.state as state,\n       d.rank as rank, d.snippet as snippet\n  from totals t\n  left join detail d on d.kind = t.kind\n order by t.kind, {}",
        order_by("d.", ranked, true)
    );

    SearchSql {
        sql,
        binds: builder.binds,
    }
}

/// Every live mirror id a query admits, uncapped and unranked (#810): the
/// Tickets view's server-side filter, which narrows a board rather than
/// filling a launcher page.
///
/// The grammar's keys match through [`corpus_predicates`], the predicates
/// [`search_sql`] uses, so a key means the same in the view and the launcher.
/// **The words do not**: the launcher ranks full-text matches over the title
/// and the body, and this keeps a row when every word appears, as a
/// substring ignoring case, in its key (the entity id past its namespace, so
/// `jira` is not a word of every Jira ticket), title, declared assignee or the names
/// of its declared parents (a Jira ticket's epic) -- R-2.3's rule and
/// prototype-6's *Filter by key, summary, epic or person*, which the view
/// marks. `words` are [`query::word_alternatives`](crate::query::word_alternatives),
/// lowercased by the caller: a row is kept when it holds every word of one
/// alternative and none it leaves out (#1889); none is no word filter.
#[must_use]
pub fn ids_sql(words: &[WordAlternative], filters: &EffectiveFilters) -> SearchSql {
    let mut builder = Builder::default();
    let sql = ids_body(&mut builder, words, filters);
    SearchSql {
        sql,
        binds: builder.binds,
    }
}

/// [`ids_sql`]'s statement, its placeholders allocated on `builder`, so that
/// several can share one statement ([`ids_counts_sql`]).
fn ids_body(
    builder: &mut Builder,
    words: &[WordAlternative],
    filters: &EffectiveFilters,
) -> String {
    let corpus = &crate::corpus::LIVE_ITEM;
    let bound = bind_filters(builder, filters);
    let typed = (!words.is_empty()).then(|| match &bound.declarations {
        Some(declarations) => declarations.clone(),
        None => builder.param(Bind::Json(filters.declarations.as_param())),
    });

    let mut sql = String::from("with\n");
    sql.push_str(&field_paths(&bound));
    sql.push_str(&reaches(&bound));
    // `with` needs at least one CTE; this one is free.
    sql.push_str("nothing as (select 1)\n");
    // The live mirror as the base table and two hashed exclusion sets, not
    // `sync.live_item`: this reads a whole kind, and on tables never analyzed
    // the view's join to `knobas.entity` was planned by how costly the
    // predicates looked. With `has:`'s walk estimated under about 44,000 the
    // planner rescanned every live entity once per match, 1.3 s for
    // `has:blocker`'s 5,000 tickets at 22,000 items (#1163, and #1161 before
    // it). The exclusion sets are the view's two filters (`0002`, `0012`).
    let _ = write!(
        sql,
        "select {} as entity_id from sync.item i",
        corpus.entity_id
    );
    let mut predicates = vec![knobas_core::live_by_exclusion!("i").to_owned()];
    predicates.extend(corpus_predicates(corpus, None, &bound));
    if let Some(declarations) = &typed {
        let _ = write!(sql, " cross join (select {declarations}::jsonb as d) pd");
        predicates.push(words_predicate(builder, words));
    }
    sql.push('\n');
    if !predicates.is_empty() {
        let _ = write!(sql, " where {}", predicates.join("\n   and "));
    }
    sql
}

/// [`ids_sql`]'s word filter: the row meets one of `words`' alternatives,
/// each holding every word it asks for and none it leaves out (#1889).
/// An alternative's words bind as one array, those it leaves out as another.
fn words_predicate(builder: &mut Builder, words: &[WordAlternative]) -> String {
    // Whether the row holds `w.word`. The key and the title first, each on
    // its own, so a word either holds reads no payload (#897); the declared
    // assignee, then the declared parents, only for a word they both miss.
    // No word holds a space, so this matches what the three joined by
    // spaces matched.
    let holds = format!(
        "case when strpos(lower(substr(i.entity_id, strpos(i.entity_id, ':') + 1)), w.word) > 0 then true \
              when strpos(lower(i.title), w.word) > 0 then true \
              when strpos(lower(coalesce({}, '')), w.word) > 0 then true \
              else exists (select 1 from sync.item_parent ip \
                           where ip.entity_id = i.entity_id and strpos(lower(ip.name), w.word) > 0) end",
        knobas_core::declared_string!("pd.d", "assignee")
    );
    let alternatives: Vec<String> = words
        .iter()
        .map(|alternative| {
            let mut parts = Vec::new();
            if !alternative.holds.is_empty() {
                let holds_all = builder.param(Bind::Texts(alternative.holds.clone()));
                parts.push(format!(
                    "not exists (select 1 from unnest({holds_all}::text[]) w(word) where not ({holds}))"
                ));
            }
            if !alternative.lacks.is_empty() {
                let lacks_all = builder.param(Bind::Texts(alternative.lacks.clone()));
                parts.push(format!(
                    "not exists (select 1 from unnest({lacks_all}::text[]) w(word) where {holds})"
                ));
            }
            parts.join(" and ")
        })
        .collect();
    match alternatives.as_slice() {
        [one] => one.clone(),
        many => format!("(({}))", many.join(")\n    or (")),
    }
}

/// How many rows [`ids_sql`] would answer with, as one `bigint` (#812): a
/// ticket view's count in the views pane, the same rows its board draws.
#[must_use]
pub fn ids_count_sql(words: &[WordAlternative], filters: &EffectiveFilters) -> SearchSql {
    let ids = ids_sql(words, filters);
    SearchSql {
        sql: format!("select count(*)::bigint from (\n{}\n) matched", ids.sql),
        binds: ids.binds,
    }
}

/// [`ids_count_sql`] for several queries in one statement (#1654): one row
/// per query, `(position, count)`, `position` being its index in `queries`.
/// `None` for none. One round trip however many ticket views are saved, as
/// [`saved_summary_sql`] does for the rail.
#[must_use]
pub fn ids_counts_sql(queries: &[(&[WordAlternative], &EffectiveFilters)]) -> Option<SearchSql> {
    if queries.is_empty() {
        return None;
    }
    let mut builder = Builder::default();
    let mut sql = String::new();
    for (position, (words, filters)) in queries.iter().enumerate() {
        if position > 0 {
            sql.push_str("union all\n");
        }
        let body = ids_body(&mut builder, words, filters);
        let position = builder.param(Bind::I64(i64::try_from(position).unwrap_or(i64::MAX)));
        let _ = writeln!(
            sql,
            "select {position}::bigint as position, count(*)::bigint as total from (\n{body}\n) matched"
        );
    }
    Some(SearchSql {
        sql,
        binds: builder.binds,
    })
}

/// The filter placeholders one statement has allocated, ready to splice.
///
/// A struct rather than four locals so that [`corpus_predicates`] can be one
/// function with two callers: the placeholders are per **statement**, the
/// predicates are per **corpus**, and separating them is what lets the rail's
/// count and the page behind it be generated from one piece of code.
struct BoundFilters {
    sources: Option<String>,
    kinds: Option<String>,
    days: Option<String>,
    authors: Option<String>,
    /// The declarations and the values, in that order: `under:` needs both.
    under: Option<(String, String)>,
    /// The `reach:` values' placeholder (#817).
    reach: Option<String>,
    /// The `name:` globs' placeholder (#868).
    names: Option<String>,
    /// The ticket-key conditions (#811), each with the placeholders it reads.
    fields: Vec<BoundField>,
    /// The declarations' placeholder, once a filter has bound it: `under:`
    /// and the ticket keys share it, and so does the detail stage's path.
    declarations: Option<String>,
}

/// One ticket-key condition's placeholders.
struct BoundField {
    key: crate::query::FieldKey,
    negated: bool,
    values: String,
    /// `assigned:`'s window, or `null`.
    days: String,
    /// `has:`'s user (#815), or `null`.
    me: String,
}

/// Allocate one statement's filter binds, in the order they are read.
///
/// With a ticket key the declarations come first: the statement's
/// `fdecl` CTE reads them before any predicate does (`crate::corpus::FIELD_PATHS`).
fn bind_filters(builder: &mut Builder, filters: &EffectiveFilters) -> BoundFilters {
    let declarations = (!filters.fields.is_empty())
        .then(|| builder.param(Bind::Json(filters.declarations.as_param())));
    let mut bound = bind_dimensions(builder, filters, declarations.as_ref());
    bound.declarations = declarations.or_else(|| bound.under.as_ref().map(|(d, _)| d.clone()));
    for filter in &filters.fields {
        // `has:`'s kinds before its user: its fragment reads them first,
        // to pick the links it walks (#939).
        // The six name keys bind as typed and are folded by the server
        // (#1843); `has:`, `sprint:` and `assigned:` read a spelling the
        // parse already folded.
        use crate::query::FieldKey;
        let values = match filter.key {
            FieldKey::Project
            | FieldKey::Status
            | FieldKey::IssueType
            | FieldKey::Priority
            | FieldKey::Assignee
            | FieldKey::Label => bind_lowered(builder, &filter.values),
            FieldKey::Sprint | FieldKey::Assigned | FieldKey::Has => {
                builder.param(Bind::Texts(filter.values.clone()))
            }
        };
        let me = if filter.key == crate::query::FieldKey::Has {
            builder.param(Bind::Texts(filter.me.clone()))
        } else {
            "null".to_owned()
        };
        let days = filter.within_days.map_or_else(
            || "null".to_owned(),
            |days| builder.param(Bind::I32(clamp_days(days))),
        );
        bound.fields.push(BoundField {
            key: filter.key,
            negated: filter.negated,
            values,
            days,
            me,
        });
    }
    bound
}

/// [`bind_filters`]' first half: every dimension but the ticket keys,
/// `under:` reading `declarations` when they are bound already.
fn bind_dimensions(
    builder: &mut Builder,
    filters: &EffectiveFilters,
    declarations: Option<&String>,
) -> BoundFilters {
    // First of the dimensions because the statement reads it first: the
    // `reaches` CTE (#1653) comes before every corpus branch.
    let reach = filters
        .filters_by_reach()
        .then(|| bind_lowered(builder, &filters.reach));
    BoundFilters {
        sources: (!filters.sources.is_empty())
            .then(|| builder.param(Bind::Texts(filters.sources.clone()))),
        kinds: (!filters.kinds.is_empty())
            .then(|| builder.param(Bind::Texts(filters.kinds.clone()))),
        days: filters
            .updated_within_days
            .map(|days| builder.param(Bind::I32(clamp_days(days)))),
        // `mine` with an empty author list is not "no filter": it is knobas not
        // knowing who the user is. Binding the empty array matches nothing,
        // which is the honest answer; dropping the predicate would return
        // everything.
        //
        // Which is why the *decision* reads `mine` and the named people rather
        // than the resolved list: the list is empty in exactly the state the
        // predicate has to survive.
        authors: filters
            .filters_by_author()
            .then(|| builder.param(Bind::Texts(filters.authors()))),
        under: filters.filters_by_under().then(|| {
            (
                declarations
                    .cloned()
                    .unwrap_or_else(|| builder.param(Bind::Json(filters.declarations.as_param()))),
                bind_lowered(builder, &filters.under),
            )
        }),
        reach,
        names: (!filters.names.is_empty())
            .then(|| builder.param(Bind::Texts(filters.names.clone()))),
        fields: Vec::new(),
        declarations: None,
    }
}

/// What one corpus contributes to a `where` clause for a given query.
///
/// **One function, two statements**, and that is the whole reason it exists:
/// [`search_sql`] builds the rows a query answers with and
/// [`saved_summary_sql`] builds the number the launcher's rail draws beside it,
/// and `knobas_search::lists`' `builtins!` macro states the rule those two are
/// held to in as many words -- *"a count computed from a different predicate
/// than the rows it claims to count is the worst failure available here"*. The
/// built-ins get that guarantee from a macro because their predicates are
/// literals; a saved list's predicate is assembled at run time, so it gets it
/// from this.
///
/// `fts` is the expression the corpus's `tsvector` is matched against, or
/// `None` for a browse: `search_sql` computes the tsquery once as a `q` CTE and
/// passes `q.tsq`, and [`saved_summary_sql`] -- which has no rank and no
/// headline to feed and may carry several queries at once -- spells the call
/// inline. Either way the raw text travels as a bind and never as SQL.
fn corpus_predicates(corpus: &Corpus, fts: Option<&str>, bound: &BoundFilters) -> Vec<String> {
    let mut predicates: Vec<String> = Vec::new();
    if let Some(fts) = fts {
        predicates.push(format!("{} @@ {fts}", corpus.fts));
    }
    if let Some(scope) = corpus.scope {
        predicates.push(scope.to_owned());
    }
    if let Some(sources) = &bound.sources {
        predicates.push(format!("{} = any({sources})", corpus.source_id));
    }
    if let Some(kinds) = &bound.kinds {
        predicates.push(format!("{} = any({kinds})", corpus.kind));
    }
    if let Some(days) = &bound.days {
        predicates.push(format!(
            "{} >= now() - make_interval(days => {days})",
            corpus.updated_at
        ));
    }
    if let Some(authors) = &bound.authors {
        predicates.push(match corpus.author {
            Some(author) => format!("{author} = any({authors})"),
            // A corpus with no author column holds nothing of anybody's.
            None => "false".to_owned(),
        });
    }
    if let Some((declarations, values)) = &bound.under {
        predicates.push(match corpus.under {
            // `ud` is the one row the corpus's fragment reads the values
            // (`ud.v`) from, so the fragment stays a `&'static str` and the
            // binds stay binds. `ud.d`, the declarations, is still bound and
            // no corpus reads it since #627 moved the mirror's arm onto
            // `sync.item_parent`; it is kept so a corpus that walks a payload
            // again needs no change here.
            Some(under) => format!(
                "exists (select 1 from (select {declarations}::jsonb as d, \
                 {values}::text[] as v) ud where {under})"
            ),
            // A corpus whose rows declare no parent sits beneath nothing.
            None => "false".to_owned(),
        });
    }
    if bound.reach.is_some() {
        // The statement's one walk ([`reaches`]), never a walk per corpus.
        predicates.push(format!(
            "{} in (select rx.id from reaches rx)",
            corpus.entity_id
        ));
    }
    if let Some(names) = &bound.names {
        // `knobas_core::name_glob_matches!`, the text a link-set pattern
        // matches with (#868), over this corpus's id and title.
        predicates.push(format!(
            "exists (select 1 from unnest({names}::text[]) ng(g) where {})",
            knobas_core::name_glob_matches!("{id}", "{title}", "ng.g")
                .replace("{id}", corpus.entity_id)
                .replace("{title}", corpus.title)
        ));
    }
    for field in &bound.fields {
        // `fd` is the one row a fragment reads its binds from, as `ud` is for
        // `under:`. A fragment that misses yields null, and null is "does not
        // match": `coalesce` makes it false before a `not` can see it.
        let matches = match corpus.fields.iter().find(|(key, _)| *key == field.key) {
            // `has:` (#815) reads its binds in place rather than from `fd`:
            // its fragment is a set (`in (select ...)`) that must be read
            // once per statement, and a reference to `fd` would make it a
            // subplan run once per row, the whole signal walk each time. The
            // fragment's only `fd.` references are these two, by
            // construction (`crate::corpus::LIVE_ITEM_FIELDS`).
            Some((crate::query::FieldKey::Has, fragment)) => format!(
                "coalesce({}, false)",
                fragment
                    .replace("fd.v", &field.values)
                    .replace("fd.u", &field.me)
            ),
            Some((_, fragment)) => format!(
                "coalesce((select {fragment} from (select {}::text[] as v, {}::int as n, \
                 {}::text[] as u) fd), false)",
                field.values, field.days, field.me
            ),
            // A corpus whose rows have no such field matches no value of it.
            None => "false".to_owned(),
        };
        predicates.push(if field.negated {
            format!("not {matches}")
        } else {
            matches
        });
    }
    predicates
}

/// A text array of the typed values, each lower-cased **by the server**
/// (#1652): `array[lower($1::text), lower($2::text)]`, one bind per value.
///
/// The value is bound as typed and folded by the same `lower()` as the stored
/// side it is compared to, not by Rust's `to_lowercase`, which differs from
/// libc on `İ` and a final sigma. One bind per value rather than
/// `lower(<array bind>::text)` or an `unnest`: both of those are stable or
/// subplan expressions the planner cannot fold, and an `under:` over 100,000
/// items went from 64 ms to 102 ms at p90 on the estimates they lose. `lower`
/// of a bound text is immutable, so the array folds to a constant, as the
/// array bind it replaces was.
fn bind_lowered(builder: &mut Builder, values: &[String]) -> String {
    let each: Vec<String> = values
        .iter()
        .map(|value| format!("lower({}::text)", builder.param(Bind::Text(value.clone()))))
        .collect();
    format!("array[{}]::text[]", each.join(", "))
}

/// What the tickets a `reach:` names reach (#817), as the CTE `reaches(id)`
/// ending in `,\n`, or nothing for a query without `reach:`:
/// `knobas_core::reach_walk!`, the walk the job-reach read makes, started from
/// every ticket whose id or key is one of the values. Every corpus reads the
/// same ids, so an asset, a note or a route is kept exactly when the read
/// would list it.
///
/// **One CTE, materialized, that every corpus branch reads** (#1653). The
/// start set compares `lower(e.id)` and the key past its namespace; spliced
/// into each branch, as it was, that was four starts and four walks a search
/// over [`crate::corpus::ALL`], and four more per saved list on the rail.
/// `materialized` so the planner cannot inline it back into each branch.
///
/// **Both halves are spelled as migration `0058` indexes them** (#1850):
/// `entity_id_lower_idx` and `entity_key_lower_idx`, which the planner
/// answers with a `BitmapOr` of the two, `kind = 'ticket'` a filter on the
/// rows they found.
/// Spelled any other way, the start set is a scan of every entity again
/// (`reach.rs`' `the_start_set_is_found_through_an_index`).
///
/// Resolved by equality, value by value: the id as typed or the key, both
/// lowercased, and never a pattern.
fn reaches(bound: &BoundFilters) -> String {
    let Some(values) = &bound.reach else {
        return String::new();
    };
    format!(
        "reaches as materialized (
    with recursive start(t) as (
        select e.id from knobas.entity e
         where e.kind = 'ticket'
           and (lower(e.id) = any({values}::text[])
                or lower(substr(e.id, strpos(e.id, ':') + 1)) = any({values}::text[]))
    ),
    {}
    select r.id from reached r
),
",
        knobas_core::reach_walk!()
    )
}

/// The CTEs a statement with a ticket key needs, each ending in `,\n`, or
/// nothing: `fdecl` holding the declarations, then
/// [`crate::corpus::FIELD_PATHS`]. Nothing for a statement without one, so
/// every other query's text is what it was before #811.
fn field_paths(bound: &BoundFilters) -> String {
    match (&bound.declarations, bound.fields.is_empty()) {
        (Some(declarations), false) => format!(
            "fdecl as (select {declarations}::jsonb as d),\n{},\n",
            crate::corpus::FIELD_PATHS
        ),
        _ => String::new(),
    }
}

/// One saved list, as the summary statement asks about it (#506).
///
/// The parse is the caller's -- `knobas_search::saved` runs the saved raw text
/// through the same `query::parse` + `query::merge` a keystroke goes through,
/// so what arrives here is the query *as the grammar of the day reads it* and
/// not as it read when somebody pressed *Save as list*.
#[derive(Debug)]
pub struct SavedQuery<'a> {
    /// The list's id, echoed back as a column so that one statement can answer
    /// for every saved list at once. Bound, never spliced.
    pub id: &'a str,
    /// The search terms, or `None` for a saved query that is nothing but chips
    /// -- browse mode, exactly as in [`search_sql`].
    pub text: Option<&'a str>,
    pub filters: &'a EffectiveFilters,
}

/// Every saved list's count and freshness, in one round trip.
///
/// `None` when there is nothing to ask about, which is the ordinary case: a
/// launcher with no saved lists must not send a statement at all, and an empty
/// `union all` is not a statement.
///
/// # The shape, and what is deliberately absent from it
///
/// ```sql
/// select $1 as list_id, count(*) as total, max(m.synced_at) as newest
///   from ( <one branch per corpus, the same where clause a search uses> ) m
/// union all
/// select $7 as list_id, ...
/// ```
///
/// No `q` CTE, no `materialized`, no `totals`, no `top`, no `picked`, no
/// `detail` and no `ts_headline`. Every one of those exists in [`search_sql`]
/// to produce a **page** -- to rank it, to bound it per kind, and to fetch
/// titles and excerpts for the rows that survived. A rail draws a number and a
/// dot; it reads no row, so the branch stays as narrow as `m` is there and the
/// most expensive stage of a search never runs for it.
///
/// **One statement for every saved list**, `union all`-ed, because the board is
/// one round trip: `lists::SUMMARY_SQL` answers the seven built-ins in one and
/// a rail that then made a round trip per saved list would grow the launcher's
/// hot path by the number of lists a reader has saved. The work is the same
/// scans either way; what is saved is the latency, which is what the ⌘K budget
/// is spent on.
///
/// **`max(synced_at)`, not `max(item_updated_at)`**, and the built-ins are why:
/// `SUMMARY_SQL`'s mirror lists badge on `max(i.synced_at)`, so "something in
/// this list is newer than the last time you opened it" means *knobas has seen
/// something since* for a saved list exactly as it does for *Changed today*. An
/// item the source last moved a year ago that a sync brought into a saved
/// list's reach this morning is news, and `item_updated_at` would call it a
/// year old.
#[must_use]
pub fn saved_summary_sql(corpora: &[&Corpus], queries: &[SavedQuery<'_>]) -> Option<SearchSql> {
    if queries.is_empty() {
        return None;
    }
    let mut builder = Builder::default();
    let mut sql = String::new();

    for (position, query) in queries.iter().enumerate() {
        if position > 0 {
            sql.push_str("union all\n");
        }
        // Binds in the order their placeholders appear, as in `search_sql`:
        // the id column first, then the tsquery, then the filters -- with two
        // exceptions, which read filter binds ahead of the tsquery's: a ticket
        // key's `fdecl` and `reach:`'s `reaches` (#1653), both CTEs of the
        // subquery the branches sit in.
        let id = builder.param(Bind::Text(query.id.to_owned()));
        let fts = query.text.map(|raw| {
            let text = builder.param(Bind::Text(raw.to_owned()));
            format!("websearch_to_tsquery('english', {text})")
        });
        let bound = bind_filters(&mut builder, query.filters);

        let _ = writeln!(
            sql,
            "select {id} as list_id, count(*) as total, max(m.synced_at) as newest\n  from ("
        );
        // Per saved list, since each binds values of its own; once for all
        // of its corpora.
        let ctes = field_paths(&bound) + &reaches(&bound);
        if let Some(ctes) = ctes.strip_suffix(",\n") {
            let _ = writeln!(sql, "  with {ctes}");
        }
        for (index, corpus) in corpora.iter().enumerate() {
            if index > 0 {
                sql.push_str("  union all\n");
            }
            let _ = writeln!(
                sql,
                "  select {} as synced_at\n    from {}",
                corpus.synced_at, corpus.relation
            );
            let predicates = corpus_predicates(corpus, fts.as_deref(), &bound);
            if !predicates.is_empty() {
                let _ = writeln!(sql, "   where {}", predicates.join("\n     and "));
            }
        }
        sql.push_str("  ) m\n");
    }

    Some(SearchSql {
        sql,
        binds: builder.binds,
    })
}

/// Bind a generated statement and hand back a runnable query.
///
/// The one place in knobas where a runtime-built SQL string is executed. Sound
/// because of the invariants in this module's docs: `built.sql` came out of
/// [`search_sql`], which can only concatenate `&'static str` fragments and
/// placeholders produced by [`Builder::param`].
pub fn query_as_with<O>(built: SearchSql) -> QueryAs<'static, Postgres, O, PgArguments>
where
    O: for<'r> FromRow<'r, PgRow> + Send + Unpin,
{
    let SearchSql { sql, binds } = built;
    let mut query = sqlx::query_as::<Postgres, O>(sqlx::AssertSqlSafe(sql))
        // **Not a cached prepared statement, and this is a measured decision.**
        //
        // PostgreSQL plans a *named* prepared statement with the actual
        // parameter values for its first five executions and then considers a
        // **generic** plan, which by definition cannot know the tsquery. It
        // therefore falls back to a default selectivity guess for `fts @@ $1`,
        // decides the match set is tiny, and joins `knobas.entity` with a
        // nested loop -- one `entity_pkey` probe per matching row.
        //
        // Measured on a 100k-row corpus, twenty consecutive searches for one
        // word: 125, 123, 124, 123, 128, **185**, 187, 185, 196, 191, 230, 284,
        // 257, 347, 502, 621, ... The step at the sixth execution is the switch.
        // The plan behind the slow one does 40,000 index probes and touches
        // 167,554 buffers where the custom plan's hash join touches 8,386.
        //
        // `persistent(false)` uses the unnamed statement, which PostgreSQL
        // plans at Bind time with the values in hand -- so every execution is a
        // custom plan. The cost is re-planning: 1.5 ms of a 100 ms budget,
        // against a 5x regression that only appears after the sixth keystroke
        // of a session and would therefore never be seen in a test that ran a
        // query five times.
        .persistent(false);
    for bind in binds {
        query = match bind {
            Bind::Text(value) => query.bind(value),
            Bind::Texts(value) => query.bind(value),
            Bind::I32(value) => query.bind(value),
            Bind::I64(value) => query.bind(value),
            Bind::Json(value) => query.bind(value),
        };
    }
    query
}

/// The 1-based positions among the typed `under:` `values` that a parent
/// answers to (#1652), for `crate::under::report_unknown`.
///
/// Compared in SQL on both sides, as `PARENTS_SQL` is, so a value Rust and the
/// server lower-case differently (`İ`) is still known. The statement is built
/// here because `AssertSqlSafe` is confined to this module; every value is a
/// bind. The values reach `lower(p.name) = any(array[lower($1::text), ...])`,
/// which folds to a constant, so the read stays on `item_parent_name_idx`
/// (`lower(ip.name)`); a join on `lower(v.t)` reads the whole parent view
/// (64 ms to 102 ms at p90 over 100,000 items).
///
/// # Errors
///
/// [`sqlx::Error`] if the lookup fails.
pub(crate) async fn known_parent_positions(
    pool: &sqlx::PgPool,
    values: &[String],
) -> Result<Vec<i64>, sqlx::Error> {
    let lowered = format!(
        "array[{}]::text[]",
        (1..=values.len())
            .map(|n| format!("lower(${n}::text)"))
            .collect::<Vec<_>>()
            .join(", ")
    );
    let mut query = sqlx::query_scalar::<Postgres, i64>(sqlx::AssertSqlSafe(format!(
        "select o.i from unnest({lowered}) with ordinality o(l, i) \
         where o.l in (select lower(p.name) from {} p where lower(p.name) = any({lowered}))",
        crate::under::parent_names!()
    )));
    for value in values {
        query = query.bind(value.clone());
    }
    query.fetch_all(pool).await
}

/// The plan the launcher's own statement runs under.
///
/// Behind `test-util` and living **here** because this is the module
/// `AssertSqlSafe` is confined to (`tests/it/sql_containment.rs` fails the build
/// if it is named anywhere else). Prepending `explain` to a statement built by
/// [`search_sql`] is exactly as sound as running it: the text still came out of
/// the builder and every value still travels as a bind.
///
/// `analyze` and `buffers` on, `costs` off -- the estimate is not the question,
/// what the executor actually did is.
///
/// # Errors
///
/// [`sqlx::Error`] if the statement cannot be planned.
#[cfg(any(test, feature = "test-util"))]
pub async fn explain(pool: &sqlx::PgPool, built: SearchSql) -> Result<String, sqlx::Error> {
    let SearchSql { sql, binds } = built;
    let mut query = sqlx::query_as::<Postgres, (String,)>(sqlx::AssertSqlSafe(format!(
        "explain (analyze, buffers, costs off)
{sql}"
    )));
    for bind in binds {
        query = match bind {
            Bind::Text(value) => query.bind(value),
            Bind::Texts(value) => query.bind(value),
            Bind::I32(value) => query.bind(value),
            Bind::I64(value) => query.bind(value),
            Bind::Json(value) => query.bind(value),
        };
    }
    Ok(query
        .fetch_all(pool)
        .await?
        .into_iter()
        .map(|(line,)| line)
        .collect::<Vec<_>>()
        .join("\n"))
}

/// The largest `updated:` window the statement may ask Postgres for.
///
/// `now() - make_interval(days => $n)` has to land inside `timestamptz`, which
/// bottoms out at 4713 BC -- about 2.4 million days back. Past that the server
/// raises `timestamp out of range`, and the launcher turns a typo into an
/// `IpcErrorCode::Internal` on its hot path.
///
/// Roughly 2,700 years, which is longer than any corpus and comfortably inside
/// the range. The exact number does not matter; that it is a **clamp** and not
/// a saturation does. Saturating at `i32::MAX` is the worst possible choice --
/// that value is itself guaranteed to throw.
const MAX_UPDATED_WITHIN_DAYS: i32 = 1_000_000;

/// A day count Postgres can subtract from `now()`.
///
/// Clamped here rather than in the parser, and deliberately so: `SearchFilters`
/// arrives from the frontend, so a **chip** carrying `updated_within_days:
/// 4_294_967_295` never passes through `query::duration_days` at all. The
/// engine's limit belongs at the engine's edge, which is the only place every
/// caller goes through.
fn clamp_days(days: u32) -> i32 {
    i32::try_from(days)
        .unwrap_or(MAX_UPDATED_WITHIN_DAYS)
        .min(MAX_UPDATED_WITHIN_DAYS)
}

/// A match's rank while the last word may still be a prefix, for a corpus
/// whose index is `{fts}`.
///
/// `to_tsvector` gives a hyphenated compound a lexeme for the whole and one
/// for each part (`payout-service` is `payout-servic`, `payout` and
/// `servic`), so the prefix `payout:*` matches the name twice. Before #611 a
/// row named `payout-service` scored 2 where a row named `payout` scored 1.
/// The first part is a lexeme of its own, so a row that holds the typed
/// words *whole* (`q.whole`, the same query with no prefix) is ranked by
/// them, and the compound adds nothing.
///
/// A row that matches only as a prefix is ranked as before: the word is not
/// finished yet, or the row holds only longer words. Two costs follow, both
/// the price of keeping this a query and not a migration of every `fts`
/// column. While a word is unfinished, a compound still counts it twice. And
/// a row that holds the word whole is ranked without the longer words it
/// also holds, so typing `pay` ranks `pay payment` by `pay` alone.
///
/// Matching is untouched: `{fts} @@ q.tsq` decides which rows come back,
/// this only decides their order.
const RANK_WHOLE: &str = "case when {fts} @@ q.whole then ts_rank_cd({fts}, q.whole)\n              else ts_rank_cd({fts}, q.tsq) end";

/// Whether a match is *named* exactly what was typed, for a corpus whose
/// title is `{title}`: the title, lexed as the index lexes it, is the typed
/// words and nothing else.
///
/// Once a compound no longer counts twice, `payout` and `payout-service` tie
/// for `payout` and recency would decide; story 25 asks for *"the thing
/// named what I typed"* first. So this is the ordering's second key, read
/// only between equal ranks: a body that says the word four times still
/// beats a name that is the word (story 26 rules out a title tier). Lexemes
/// and not text, so `Payouts` is named `payout`, and both sides are sorted
/// and distinct arrays (`tsvector_to_array`), so word order does not matter.
///
/// The title and not the index's weight-A lexemes: the title is short, where
/// reading a slice of `fts` would detoast a whole body's vector once more per
/// match, and it is the name a reader sees whatever else a migration adds to
/// weight A.
///
/// A title that holds a `/` is also named by the text after its last `/`
/// (#621): the parser reads `tidewater/payout` as one file-path lexeme, so
/// the whole title names nothing a bare word can type, and `payout` would
/// leave `tidewater/payout` and `tidewater/payout-service` to recency. The
/// last segment and not every segment, so `tidewater` names none of the
/// owner's repos; and no kind is named, so a branch `feature/payout` is named
/// `payout` by the same rule. The guard is for cost, not meaning: with no `/`,
/// `split_part` returns the whole title and the second half can only repeat
/// the first, so a planner that skips the guard changes no answer.
///
/// **Lexed per match**, and so only for a corpus that stores no lexemes of
/// its own (`Corpus::named`, #1650): the notes, the assets and the routes. The
/// mirror stores this expression's two halves, and a ticket's key lexed the
/// same way, as columns (migration `0056`), and compares those, because a
/// word in every row of the mirror made this a fifth of the statement.
const NAMED: &str = "(tsvector_to_array(to_tsvector('english', {title})) = q.words\n              or (strpos({title}, '/') > 0\n                  and tsvector_to_array(to_tsvector('english', split_part({title}, '/', -1))) = q.words))";

/// The result ordering, qualified with `prefix` (`""`, `"m."` or `"d."`).
///
/// `entity_id` is the last key on purpose: rank ties and identical timestamps
/// are common in a mirror written by one transaction, and without a total order
/// the page a user pages through is not stable between two identical queries.
fn order_by(prefix: &str, ranked: bool, nullable: bool) -> String {
    let nulls = if nullable { " nulls last" } else { "" };
    let mut keys = Vec::new();
    if ranked {
        keys.push(format!("{prefix}rank desc{nulls}"));
        // Only between equal ranks, so a name is never a tier of its own
        // (story 26): see `NAMED`.
        keys.push(format!("{prefix}named desc{nulls}"));
    }
    keys.push(format!("{prefix}item_updated_at desc nulls last"));
    keys.push(format!("{prefix}entity_id"));
    keys.join(", ")
}

/// Accumulates the arguments a generated statement reads.
#[derive(Default)]
struct Builder {
    binds: Vec<Bind>,
}

impl Builder {
    /// Push a value and get back the placeholder that reads it.
    ///
    /// The only way to add a bind, which is what makes it impossible for a
    /// placeholder to drift from its argument.
    fn param(&mut self, bind: Bind) -> String {
        self.binds.push(bind);
        format!("${}", self.binds.len())
    }
}

