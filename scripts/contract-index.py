#!/usr/bin/env python3
"""Keep docs/contract.md section 10.8 as a preamble plus a generated index.

Each ratified-exception entry of section 10.8 lives in its own file under
docs/contract/10.8/<issue>-<slug>.md (issues #737), so concurrent PRs add a
file instead of all appending to the end of docs/contract.md.

  contract-index.py            move any entry bullet still in contract.md into
                               its own file (verbatim), then rewrite the index
  contract-index.py --check    exit 1 if the index is stale, a bullet is loose, or an entry
                               file's first line is not a bullet naming an issue
  contract-index.py --verify-move-to FILE
                               with the default mode: write the verbatim
                               concatenation of the moved bullets, in their
                               original order, to FILE (for the before/after proof)

Run with `python3 -I scripts/contract-index.py` (just contract-index).
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONTRACT = ROOT / "docs" / "contract.md"
DIR = ROOT / "docs" / "contract" / "10.8"
BEGIN = "<!-- 10.8-index:begin (generated by `just contract-index`; do not edit by hand) -->"
END = "<!-- 10.8-index:end -->"
REGION_START = "**Ratified exceptions to the frozen list**"
REGION_END = "**`crates/knobas-sync/**` is NOT frozen"


def split(lines):
    """-> (head, kept, entries, after, tail): bullets at column 0 inside the region, in order.

    kept is prose above the index, after is prose below its end marker (it stays there)."""
    s = next(i for i, l in enumerate(lines) if l.startswith(REGION_START))
    e = next(i for i, l in enumerate(lines) if l.startswith(REGION_END))
    # head ends after the region-start line; index block (if any) is dropped.
    body = lines[s + 1 : e]
    entries, cur = [], None
    kept, after = [], []
    in_index = seen_end = False
    for l in body:
        if l.startswith(BEGIN[:20]):
            in_index = True
            continue
        if in_index:
            if l.startswith(END):
                in_index, seen_end, cur = False, True, None
            continue
        if l.startswith("- "):
            cur = [l]
            entries.append(cur)
        elif cur is not None:
            cur.append(l)
        else:
            (after if seen_end else kept).append(l)
    for part in (kept, after):
        while part and part[-1] == "":
            part.pop()
    while after and after[0] == "":
        after.pop(0)
    return lines[: s + 1], kept, entries, after, lines[e:]


def title_of(entry):
    text = " ".join(l.strip() for l in entry[:3])[2:]
    text = re.sub(r"\s+", " ", re.sub(r"(?<!/)\*\*", "", text))
    if len(text) > 110:
        text = text[:110].rsplit(" ", 1)[0] + " ..."
    return text


def issue_of(entry):
    text = " ".join(l.strip() for l in entry[:6])
    m = re.search(r"issue\s+#(\d+)", text) or re.search(r"#(\d+)", text)
    return int(m.group(1)) if m else None


def slug_of(title, issue):
    t = re.sub(r"\(\d{4}-\d\d-\d\d\)", " ", title.replace("...", ""))
    t = re.sub(r"[`*]", " ", t)
    words = re.findall(r"[a-z0-9]+", t.lower())
    drop = {"issue", "the", "a", "an", "and", "of", "to", "on", "in", "src", "crates", "with", "both", "is"}
    words = [w for w in words if w not in drop and w != str(issue) and not (len(w) == 4 and w.isdigit() and w.startswith("20"))]
    return "-".join(words[:6]) or "entry"


def move(entries, existing):
    names, nonum = [], 0
    taken = set(existing)
    for entry in entries:
        n = issue_of(entry)
        slug = slug_of(title_of(entry), n)
        if n is None:
            nonum += 1
            base = f"n{nonum:02d}-{slug}"
        else:
            base = f"{n}-{slug}"
        name, k = base, 2
        while name + ".md" in taken:
            name, k = f"{base}-{k}", k + 1
        taken.add(name + ".md")
        (DIR / (name + ".md")).write_text("".join(l + "\n" for l in entry))
        names.append(name + ".md")
    return names


def sort_key(name):
    m = re.match(r"(\d+)-", name)
    return (1, int(m.group(1)), name) if m else (0, 0, name)


def index_lines():
    out = [BEGIN, ""]
    for p in sorted(DIR.glob("*.md"), key=lambda p: sort_key(p.name)):
        first = p.read_text().split("\n")
        title = title_of(first)
        label = p.stem.split("-")[0]
        label = f"#{label}" if label.isdigit() else "(no issue)"
        out.append(f"- [{label}](contract/10.8/{p.name}) — {title}")
    out += ["", END]
    return out


def bad_entry_files():
    """Entry files whose first line is not a bullet naming an issue (a stray README.md)."""
    bad = []
    for p in sorted(DIR.glob("*.md")):
        lines = p.read_text().split("\n")
        if not lines[0].startswith("- ") or issue_of(lines) is None:
            bad.append(p.name)
    return bad


def main():
    check = "--check" in sys.argv
    proof = sys.argv[sys.argv.index("--verify-move-to") + 1] if "--verify-move-to" in sys.argv else None
    DIR.mkdir(parents=True, exist_ok=True)
    text = CONTRACT.read_text()
    lines = text.split("\n")
    head, kept, entries, after, tail = split(lines)
    if check:
        if entries:
            print("contract-index: loose 10.8 entry bullets remain in docs/contract.md; run `just contract-index`", file=sys.stderr)
            return 1
        bad = bad_entry_files()
        if bad:
            print(f"contract-index: docs/contract/10.8/ files whose first line is not a bullet naming an issue: {', '.join(bad)}", file=sys.stderr)
            return 1
        want = "\n".join(head + kept + [""] + index_lines() + [""] + (after + [""] if after else []) + tail)
        if want != text:
            print("contract-index: the section 10.8 index in docs/contract.md is stale; run `just contract-index`", file=sys.stderr)
            return 1
        return 0
    if proof:
        Path(proof).write_text("".join(l + "\n" for e in entries for l in e))
    move(entries, [p.name for p in DIR.glob("*.md")])
    # kept = prose between the region-start line and the first bullet (blank lines)
    new = head + kept + [""] + index_lines() + [""] + (after + [""] if after else []) + tail
    CONTRACT.write_text("\n".join(new))
    print(f"contract-index: moved {len(entries)} entries; index has {len(list(DIR.glob('*.md')))} files")
    return 0


sys.exit(main())
